"""Write a hand-reviewable sample of the generated biographies.

    python -m data.bios_sample --config configs/data/v1.yaml --n 20

Picks N people at random (seeded, so the sample is stable across rebuilds) and
writes every rewording, every fact prompt and the held-out-template prompts to
`<root>/samples/bios_sample.md`. The point is to be read: if a pronoun is wrong,
a sentence does not parse, or a prompt stops in the wrong place, it shows here.
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any, Dict, List, Optional

from data.bios import _rng
from data.common import DataConfig, load_config, read_jsonl


def write_sample(cfg: DataConfig, n: int = 20,
                 out: Optional[Path] = None) -> Path:
    bios_dir = cfg.bios_dir
    people = list(read_jsonl(bios_dir / "people.jsonl"))
    if not people:
        raise SystemExit(f"no people.jsonl under {bios_dir}; run data.bios first")

    rng = _rng(cfg.seed, "sample")
    # sample across splits so a control person is always shown
    trained = [p for p in people if p["split"] == "train"]
    control = [p for p in people if p["split"] == "control"]
    n_ctrl = max(1, min(len(control), n // 5))
    picked = (rng.sample(trained, min(len(trained), n - n_ctrl))
              + rng.sample(control, n_ctrl))
    picked.sort(key=lambda p: p["person_id"])
    wanted = {p["person_id"] for p in picked}

    bios: Dict[str, Dict[int, str]] = defaultdict(dict)
    for fname in ("bios_train.jsonl", "bios_control.jsonl"):
        for rec in read_jsonl(bios_dir / fname):
            if rec["person_id"] in wanted:
                bios[rec["person_id"]][rec["rewording_id"]] = rec["text"]

    facts: Dict[str, List[Dict[str, Any]]] = defaultdict(list)
    for row in read_jsonl(bios_dir / "facts.jsonl"):
        if row["person_id"] in wanted:
            facts[row["person_id"]].append(row)

    manifest = json.loads((bios_dir / "manifest.json").read_text())
    lines: List[str] = [
        f"# Biography sample -- {len(picked)} people",
        "",
        "Generated by `python -m data.bios_sample`. Seeded, so the same people "
        "appear after every rebuild.",
        "",
        f"- config fingerprint (bios scope): `{manifest['config_fingerprint'][:16]}`",
        f"- data seed: `{manifest['seed']}`",
        f"- people in the full set: {manifest['people']['n_people']:,} "
        f"({manifest['people']['by_split']})",
        f"- biography length: mean {manifest['biographies']['tokens_mean']} GPT-2 "
        f"tokens, range {manifest['biographies']['tokens_min']}"
        f"-{manifest['biographies']['tokens_max']}",
        "",
        "**What to check while reading:** pronouns agree with the `gender` field; "
        "the first sentence always names the person and later sentences mix name "
        "and pronoun; all five values appear verbatim in every rewording; each "
        "prompt stops immediately before its value; the four `paraphrase` prompts "
        "are structurally unlike anything in the four rewordings.",
        "",
        "---",
        "",
    ]

    for p in picked:
        pid = p["person_id"]
        lines += [
            f"## {p['name']} (`{pid}`)",
            "",
            f"| | |", "|---|---|",
            f"| gender | {p['gender']} |",
            f"| split | **{p['split']}** |",
            f"| tier | {p['tier']} |",
            f"| target exposures | {p['target_exposures']} |",
            "",
            "**Facts**",
            "",
            "| attribute | value |", "|---|---|",
        ]
        for attr, val in p["facts"].items():
            lines.append(f"| `{attr}` | {val} |")
        lines += ["", "**Rewordings**", ""]
        for r in sorted(bios[pid]):
            role = "discovery" if r in cfg.bio_discovery_rewordings else "test"
            lines += [f"{r}. *({role})* {bios[pid][r]}", ""]

        rows = sorted(facts[pid], key=lambda r: (
            r["held_out_template"], r["rewording_id"] if r["rewording_id"] is not None
            else -1, r["attribute"]))
        lines += ["**Fact prompts** (`prompt` | expected `continuation`)", "",
                  "| role | rewording / template | attribute | prompt (tail shown) | continuation |",
                  "|---|---|---|---|---|"]
        for row in rows:
            which = (f"r{row['rewording_id']}, t{row['template_id']}"
                     if row["rewording_id"] is not None
                     else f"held-out t{row['template_id']}")
            tail = row["prompt"]
            if len(tail) > 90:
                tail = "..." + tail[-87:]
            lines.append(f"| {row['role']} | {which} | `{row['attribute']}` | "
                         f"{tail.replace('|', '\\|')} | **{row['continuation']}** |")
        lines += ["", "---", ""]

    out = out or (cfg.samples_dir / "bios_sample.md")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    return out


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--config", required=True)
    ap.add_argument("--small", action="store_true")
    ap.add_argument("--n", type=int, default=20)
    args = ap.parse_args(argv)
    cfg = load_config(args.config, small=args.small)
    print(f"[sample] wrote {write_sample(cfg, args.n)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
